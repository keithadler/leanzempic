#!/usr/bin/env python3
"""Generate the fixed-width integer part of the Haskell runtime.

Writes runtime/Zempic/UInt.hs (operations that do not mention Nat) and refreshes the region
between `-- BEGIN GENERATED` and `-- END GENERATED` in runtime/Zempic/Nat/{Word,Exact}.hs
(conversions that do). Zempic/Emit.lean builds the matching table with the same names.
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Lean type, short prefix, Haskell type, bit width
TYPES = [("UInt8", "u8", "Word8", 8), ("UInt16", "u16", "Word16", 16),
         ("UInt32", "u32", "Word32", 32), ("UInt64", "u64", "Word64", 64),
         ("USize", "usz", "Word", 64)]

def uint_module():
    out = ["-- Copyright 2026 Keith Adler. Licensed under the Apache License, Version 2.0.",
           "--", "-- GENERATED by tools/gen_runtime.py. Fixed-width integers: wrap around like Lean's.",
           "module Zempic.UInt where", "",
           "import Data.Bits (complement, shiftL, shiftR, xor, (.&.), (.|.))",
           "import Data.Word (Word16, Word32, Word64, Word8)", ""]
    for L, s, h, bits in TYPES:
        out += [
            f"{s}Add, {s}Sub, {s}Mul, {s}Div, {s}Mod, {s}Land, {s}Lor, {s}Xor, {s}Shl, {s}Shr :: {h} -> {h} -> {h}",
            f"{s}Add = (+)", f"{s}Sub = (-)", f"{s}Mul = (*)",
            f"{s}Div x y = if y == 0 then 0 else quot x y",
            f"{s}Mod x y = if y == 0 then x else rem x y",
            f"{s}Land = (.&.)", f"{s}Lor = (.|.)", f"{s}Xor = xor",
            f"{s}Shl x y = shiftL x (fromIntegral (y `rem` {bits}))",
            f"{s}Shr x y = shiftR x (fromIntegral (y `rem` {bits}))",
            f"{s}Compl, {s}Neg :: {h} -> {h}", f"{s}Compl = complement", f"{s}Neg = negate",
            f"{s}Eq, {s}Lt, {s}Le :: {h} -> {h} -> Bool",
            f"{s}Eq = (==)", f"{s}Lt = (<)", f"{s}Le = (<=)"]
        for L2, s2, h2, _ in TYPES:
            if s2 != s:
                out += [f"{s}To{s2.capitalize()} :: {h} -> {h2}", f"{s}To{s2.capitalize()} = fromIntegral"]
        out += [f"{{-# INLINE {s}{n} #-}}" for n in
                ["Add", "Sub", "Mul", "Div", "Mod", "Land", "Lor", "Xor", "Shl", "Shr", "Compl", "Neg", "Eq", "Lt", "Le"]]
        out.append("")
    (ROOT / "runtime/Zempic/UInt.hs").write_text("\n".join(out))

ARRAY_FUNCS = """-- Lean's Array as a Baker persistent array (see Zempic.Arr): O(1) at the newest version.
arrIdx :: ZNat -> Int
arrIdx i = fromIntegral (min i 4611686018427387903)
{-# INLINE arrIdx #-}

arrIO :: IO a -> a
arrIO = unsafeDupablePerformIO
{-# INLINE arrIO #-}

arrMkEmpty :: Any -> ZNat -> Any
arrMkEmpty _ c = arrIO (zo <$> aEmpty (arrIdx c))
{-# NOINLINE arrMkEmpty #-}

arrReplicate :: Any -> ZNat -> Any -> Any
arrReplicate _ n v = arrIO (zo <$> aReplicate (arrIdx n) v)
{-# NOINLINE arrReplicate #-}

arrSize :: Any -> Any -> ZNat
arrSize _ a = fromIntegral (aLength (zu a :: Arr))

arrUSize :: Any -> Any -> Word
arrUSize _ a = fromIntegral (aLength (zu a :: Arr))

arrPush :: Any -> Any -> Any -> Any
arrPush _ !a !v = arrIO (zo <$> aPush (zu a) v)
{-# INLINE arrPush #-}

arrGetD :: Any -> Any -> Any -> ZNat -> Any
arrGetD _ !d !a !i = arrIO (aGet (zu a) (arrIdx i) d)
{-# INLINE arrGetD #-}

arrGetI :: Any -> Any -> ZNat -> Any -> Any
arrGetI _ a i _ = arrIO (aGet (zu a) (arrIdx i) (error "leanzempic: array index out of range"))
{-# NOINLINE arrGetI #-}

arrUGet :: Any -> Any -> Word -> Any -> Any
arrUGet _ a i _ = arrIO (aGet (zu a) (fromIntegral i) (error "leanzempic: array index out of range"))
{-# NOINLINE arrUGet #-}

arrSet :: Any -> Any -> ZNat -> Any -> Any
arrSet _ !a !i !v = arrIO (zo <$> aSet (zu a) (arrIdx i) v)
{-# INLINE arrSet #-}

arrUSet :: Any -> Any -> Word -> Any -> Any -> Any
arrUSet _ a i v _ = arrIO (zo <$> aSet (zu a) (fromIntegral i) v)
{-# INLINE arrUSet #-}

arrSwap :: Any -> Any -> ZNat -> ZNat -> Any
arrSwap _ a i j = arrIO (zo <$> aSwap (zu a) (arrIdx i) (arrIdx j))
{-# NOINLINE arrSwap #-}

arrPop :: Any -> Any -> Any
arrPop _ a = arrIO (zo <$> aPop (zu a))
{-# NOINLINE arrPop #-}

arrSwapP :: Any -> Any -> ZNat -> ZNat -> Any -> Any -> Any
arrSwapP _ a i j _ _ = arrIO (zo <$> aSwap (zu a) (arrIdx i) (arrIdx j))
{-# NOINLINE arrSwapP #-}

arrOfList :: Any -> [Any] -> Any
arrOfList _ xs = arrIO (zo <$> aFromList xs)
{-# NOINLINE arrOfList #-}

arrToList :: Any -> Any -> [Any]
arrToList _ a = arrIO (aToList (zu a))
{-# NOINLINE arrToList #-}
""".split("\n")

STRING_FUNCS = """-- Lean's String as a shared UTF-8 buffer (see Zempic.Str): amortized O(1) push and append.
strIO :: IO a -> a
strIO = unsafeDupablePerformIO
{-# INLINE strIO #-}

strLen :: Any -> ZNat
strLen s = fromIntegral (sChars (zu s :: Str))

strBytes :: Any -> ZNat
strBytes s = fromIntegral (sBytes (zu s :: Str))

strAppend :: Any -> Any -> Any
strAppend a b = strIO (zo <$> sAppend (zu a) (zu b))
{-# NOINLINE strAppend #-}

strPush :: Any -> Word32 -> Any
strPush s c = strIO (zo <$> sPush (zu s) c)
{-# NOINLINE strPush #-}

strEq, strLt, strLe :: Any -> Any -> Bool
strEq a b = sEq (zu a :: Str) (zu b :: Str)
strLt a b = sLt (zu a :: Str) (zu b :: Str)
strLe a b = sLe (zu a :: Str) (zu b :: Str)

strToList :: Any -> [Any]
strToList s = map (\\c -> zo (fromIntegral (ord c) :: Word32)) (T.unpack (sToText (zu s :: Str)))

strOfList :: [Any] -> Any
strOfList cs = strIO (zo <$> sFromText (T.pack (map (\\c -> chr (fromIntegral (zu c :: Word32))) cs)))
{-# NOINLINE strOfList #-}

natRepr :: ZNat -> Any
natRepr n = strIO (zo <$> sFromText (T.pack (show n)))
{-# NOINLINE natRepr #-}

strLit :: String -> Any
strLit lit = strIO (zo <$> sFromText (T.pack lit))
{-# NOINLINE strLit #-}
""".split("\n")

ARRAY_NAMES = ["arrIdx", "arrMkEmpty", "arrReplicate", "arrSize", "arrUSize", "arrPush", "arrGetD",
               "arrGetI", "arrUGet", "arrSet", "arrUSet", "arrSwap", "arrPop"]

def nat_region():
    out = ["-- BEGIN GENERATED (tools/gen_runtime.py)",
           "-- Conversions between Nat and the fixed-width integers."]
    for L, s, h, _ in TYPES:
        out += [f"{s}OfNat :: ZNat -> {h}", f"{s}OfNat = fromIntegral",
                f"{s}ToNat :: {h} -> ZNat", f"{s}ToNat = fromIntegral",
                f"{{-# INLINE {s}OfNat #-}}", f"{{-# INLINE {s}ToNat #-}}"]
    out += ARRAY_FUNCS
    out += STRING_FUNCS
    out += ["charOfNat :: ZNat -> Word32",
            "charOfNat n = if n < 55296 || (n > 57343 && n < 1114112) then fromIntegral n else 0",
            "charOfNatAux :: ZNat -> Any -> Word32", "charOfNatAux n _ = fromIntegral n",
            "{-# INLINE charOfNat #-}", "{-# INLINE charOfNatAux #-}"]
    out.append("-- END GENERATED")
    return "\n".join(out)

def patch(path):
    p = ROOT / path
    s = p.read_text()
    region = nat_region()
    if "-- BEGIN GENERATED" in s:
        s = re.sub(r"-- BEGIN GENERATED.*?-- END GENERATED", lambda m: region, s, flags=re.S)
    else:
        s = s.rstrip("\n") + "\n\n" + region + "\n"
    s = s.replace("import qualified Data.Sequence as Seq\nimport Data.Sequence (Seq, (|>))\n", "")
    if "import qualified Data.Text as T" not in s:
        s = s.replace("import Data.Bits", "import qualified Data.Text as T\nimport Data.Char (chr, ord)\nimport Data.Bits", 1)
    if "import Zempic.Str" not in s:
        s = s.replace("import Zempic.Arr", "import Zempic.Arr\nimport Zempic.Str", 1)
    if "import Zempic.Arr" not in s:
        s = s.replace("import Data.Bits", "import System.IO.Unsafe (unsafeDupablePerformIO)\nimport Zempic.Arr\nimport Data.Bits", 1)
    if "import Data.Word" not in s:
        s = s.replace("import Data.Bits", "import Data.Word (Word16, Word32, Word64, Word8)\nimport Data.Bits", 1)
    p.write_text(s)

uint_module()
patch("runtime/Zempic/Nat/Word.hs")
patch("runtime/Zempic/Nat/Exact.hs")
print("ok")
