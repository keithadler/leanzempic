#!/usr/bin/env python3
"""Generate the fixed-width integer part of the Haskell runtime.

Writes runtime/Zempic/UInt.hs (operations that do not mention Nat) and refreshes the region
between `-- BEGIN GENERATED` and `-- END GENERATED` in runtime/Zempic/Nat/{Word,Exact}.hs
(conversions that do). Zempic/Emit.lean builds the matching table with the same names.
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Lean type, short prefix, Haskell type, bit width
TYPES = [("UInt8", "u8", "Word8", 8), ("UInt16", "u16", "Word16", 16),
         ("UInt32", "u32", "Word32", 32), ("UInt64", "u64", "Word64", 64),
         ("USize", "usz", "Word", 64)]

def uint_module():
    out = ["-- Copyright 2026 Keith Adler. Licensed under the Apache License, Version 2.0.",
           "--", "-- GENERATED by tools/gen_runtime.py. Fixed-width integers: wrap around like Lean's.",
           "module Zempic.UInt where", "",
           "import Data.Bits (complement, shiftL, shiftR, xor, (.&.), (.|.))",
           "import Data.Word (Word16, Word32, Word64, Word8)", ""]
    for L, s, h, bits in TYPES:
        out += [
            f"{s}Add, {s}Sub, {s}Mul, {s}Div, {s}Mod, {s}Land, {s}Lor, {s}Xor, {s}Shl, {s}Shr :: {h} -> {h} -> {h}",
            f"{s}Add = (+)", f"{s}Sub = (-)", f"{s}Mul = (*)",
            f"{s}Div x y = if y == 0 then 0 else quot x y",
            f"{s}Mod x y = if y == 0 then x else rem x y",
            f"{s}Land = (.&.)", f"{s}Lor = (.|.)", f"{s}Xor = xor",
            f"{s}Shl x y = shiftL x (fromIntegral (y `rem` {bits}))",
            f"{s}Shr x y = shiftR x (fromIntegral (y `rem` {bits}))",
            f"{s}Compl, {s}Neg :: {h} -> {h}", f"{s}Compl = complement", f"{s}Neg = negate",
            f"{s}Eq, {s}Lt, {s}Le :: {h} -> {h} -> Bool",
            f"{s}Eq = (==)", f"{s}Lt = (<)", f"{s}Le = (<=)"]
        for L2, s2, h2, _ in TYPES:
            if s2 != s:
                out += [f"{s}To{s2.capitalize()} :: {h} -> {h2}", f"{s}To{s2.capitalize()} = fromIntegral"]
        out += [f"{{-# INLINE {s}{n} #-}}" for n in
                ["Add", "Sub", "Mul", "Div", "Mod", "Land", "Lor", "Xor", "Shl", "Shr", "Compl", "Neg", "Eq", "Lt", "Le"]]
        out.append("")
    (ROOT / "runtime/Zempic/UInt.hs").write_text("\n".join(out))

